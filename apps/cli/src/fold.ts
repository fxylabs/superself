const GENERATED_NOTE = "<!-- generated by `self` — do not edit; state changes go through events -->";

export function foldProject(storeDir: string, slug: string): void
{
    const model = buildModel(storeDir, slug, new Date());
    const projectDir = resolveProjectPath(storeDir, slug);
    const verdicts = updateVerdicts(storeDir, slug, projectDir, evidenceOf(model.works));
    model.health.push(...verdictSignals(model.works, verdicts));
    const dir = ensureDir(projectStateDir(storeDir, slug));
    ensureDir(join(dir, "work"));
    const hashes = readHashes(dir);
    writeGenerated(dir, hashes, "state.md", renderState(model));
    for (const work of model.works)
    {
        const rel = join("work", `${work.id}.md`);
        if (work.status === "done")
        {
            drop(dir, hashes, rel);
        }
        else
        {
            writeGenerated(dir, hashes, rel, renderWork(work, model, verdicts));
        }
    }
    foldObjectives(dir, hashes, model);
    foldChangeSets(dir, hashes, model);
    writeFileSync(join(dir, ".hashes.json"), JSON.stringify(hashes, null, 2) + "\n");
    const chromeMoved = writeViews(storeDir, model, readStoreConfig(storeDir), verdicts);
    if (projectDir !== null && existsSync(projectDir))
    {
        refreshBlocks(projectDir, model);
    }
    if (chromeMoved)
    {
        refoldOthers(storeDir, slug);
    }
}

let bringingForward = false;

// A fold only rewrites the project it runs in, so a new viewer would reach
// every other project's pages whenever each next happened to record an
// event — until then the workspace shows two designs at once. When the
// viewer itself moves, bring the rest forward in the same run.
function refoldOthers(storeDir: string, slug: string): void
{
    if (bringingForward)
    {
        return;
    }
    bringingForward = true;
    const others = readRegistry(storeDir).filter((entry) => entry.slug !== slug);
    for (const entry of others)
    {
        foldProject(storeDir, entry.slug);
    }
    bringingForward = false;
    if (others.length > 0)
    {
        console.log(`viewer updated — refolded ${others.length} other project${others.length === 1 ? "" : "s"}`);
    }
}

// An objective keeps a file of its own while it is live, exactly as an open
// work unit does; closing it removes the file without touching the log that
// still holds its whole lineage.
function foldObjectives(dir: string, hashes: Record<string, string>, model: ProjectModel): void
{
    if (model.goals.objectives.length === 0)
    {
        return;
    }
    ensureDir(join(dir, "objective"));
    const open = new Set(openObjectives(model.goals).map((objective) => objective.id));
    for (const objective of model.goals.objectives)
    {
        const rel = join("objective", `${objective.id}.md`);
        if (open.has(objective.id))
        {
            writeGenerated(dir, hashes, rel, GENERATED_NOTE + "\n\n" + renderObjectiveBody(objective));
        }
        else
        {
            drop(dir, hashes, rel);
        }
    }
}

// A change set keeps a file while it is in the train. Merging or closing it
// takes the file away and leaves the whole lineage in the log, exactly as a
// reached objective does.
function foldChangeSets(dir: string, hashes: Record<string, string>, model: ProjectModel): void
{
    if (model.integration.changeSets.length === 0)
    {
        return;
    }
    ensureDir(join(dir, "integration"));
    const open = new Set(openChangeSets(model.integration).map((changeSet) => changeSet.id));
    for (const changeSet of model.integration.changeSets)
    {
        const rel = join("integration", `${changeSet.id}.md`);
        if (open.has(changeSet.id))
        {
            writeGenerated(dir, hashes, rel, GENERATED_NOTE + "\n\n" + renderChangeSetBody(changeSet));
        }
        else
        {
            drop(dir, hashes, rel);
        }
    }
}

export function renderChangeSetBody(changeSet: ChangeSet): string
{
    const lines: string[] = [`# ${changeSet.id} — ${changeSet.repository}${changeSet.pr === undefined ? "" : ` #${changeSet.pr}`}`, "",
        `- Phase: ${changeSet.phase} — ${changeSet.reason}`,
        `- Base: ${changeSet.base}`,
        `- Head: ${changeSet.head}`,
        `- Feature digest: ${changeSet.featureDigest} (${changeSet.digestSource})`,
        `- Train order: ${changeSet.order + 1}`,
        `- Risk: ${changeSet.risk}`];
    optional(lines, "Work", changeSet.work);
    optional(lines, "Declared domains", changeSet.domains.map((domain) => `${domain.name}@${domain.version}`).join(", "));
    optional(lines, "Depends on", changeSet.depends.join(", "));
    optional(lines, "Supersedes", changeSet.supersedes.join(", "));
    optional(lines, "Consolidates", changeSet.consolidates.join(", "));
    optional(lines, "Required checks", changeSet.checks.join(", "));
    optional(lines, "Open predecessors", changeSet.predecessors.join(", "));
    lines.push("");
    bullets(lines, "Changed paths", changeSet.paths);
    bullets(lines, "Overlaps", overlapLines(changeSet));
    bullets(lines, "Review receipts", receiptLines(changeSet));
    bullets(lines, "Integration deltas", deltaLines(changeSet));
    bullets(lines, "Attempts", attemptLines(changeSet));
    bullets(lines, "Exact-head CI", changeSet.ci.map((item) => `${item.check}: ${item.conclusion} (observed ${item.observedAt})`));
    bullets(lines, "Blocking prerequisites", changeSet.blockers.map((item) => `${item.code} — ${item.detail}; next: ${item.next}`));
    return lines.join("\n").replace(/\n+$/, "\n");
}

function optional(lines: string[], label: string, value: string | undefined): void
{
    if (value !== undefined && value !== "")
    {
        lines.push(`- ${label}: ${value}`);
    }
}

function overlapLines(changeSet: ChangeSet): string[]
{
    return [
        ...changeSet.pathOverlaps.map((item) => `path overlap with ${item.changeSet}: ${item.paths.join(", ")}`),
        ...changeSet.semanticOverlaps.map((item) => `semantic overlap with ${item.changeSet}: ${item.domains.join(", ")}`)
    ];
}

function receiptLines(changeSet: ChangeSet): string[]
{
    return changeSet.receipts.map((receipt) =>
        `${receipt.id} ${receipt.scope} ${receipt.verdict} bound to ${receipt.digest} at head ${receipt.head}` +
        ` — ${receipt.model}, envelope ${receipt.envelopeDigest}` +
        `${receipt.artifact === undefined ? "" : `, artifact ${receipt.artifact.path}`}`);
}

function deltaLines(changeSet: ChangeSet): string[]
{
    return changeSet.deltas.map((delta) =>
        `${delta.id} ${delta.digest} from ${delta.fromDigest} to ${delta.resultDigest} — ` +
        `${changeSet.uncoveredDeltas.includes(delta.id) ? "awaiting bounded review" : "reviewed"}` +
        `${delta.paths.length === 0 ? "" : ` [${delta.paths.join(", ")}]`}`);
}

function attemptLines(changeSet: ChangeSet): string[]
{
    return changeSet.attempts.map((attempt) =>
        `${attempt.id} ${attempt.action} fence ${attempt.fence} — ${attempt.status}` +
        `${attempt.reason === undefined ? "" : `: ${attempt.reason}`}` +
        `${attempt.conflictPaths.length === 0 ? "" : ` [conflicts ${attempt.conflictPaths.join(", ")}]`}`);
}

function integrationLines(model: ProjectModel): string[]
{
    const lines: string[] = [];
    for (const repository of model.integration.repositories)
    {
        const lease = repository.lease;
        const held = lease !== undefined && lease.live ? `leased by ${lease.holder} at fence ${lease.fence}` : "no live lease";
        lines.push(`- **${repository.name}** — ${held}${repository.mainHead === undefined ? "" : `, main ${repository.mainHead}`}`);
        for (const changeSet of repository.train.map((id) => findChangeSet(model.integration, id)))
        {
            if (changeSet === undefined || changeSet.closed !== undefined)
            {
                continue;
            }
            lines.push(`  - ${changeSet.order + 1}. **${changeSet.id}**` +
                `${changeSet.pr === undefined ? "" : ` #${changeSet.pr}`} — ${changeSet.phase}: ${changeSet.reason}`);
        }
    }
    return lines;
}

function drop(dir: string, hashes: Record<string, string>, rel: string): void
{
    rmSync(join(dir, rel), { force: true });
    delete hashes[rel];
}

function readHashes(dir: string): Record<string, string>
{
    const file = join(dir, ".hashes.json");
    return existsSync(file) ? JSON.parse(readFileSync(file, "utf8")) : {};
}

function writeGenerated(dir: string, hashes: Record<string, string>, rel: string, content: string): void
{
    const file = join(dir, rel);
    const recorded = hashes[rel];
    if (recorded !== undefined && existsSync(file) && sha(readFileSync(file, "utf8")) !== recorded)
    {
        console.error(`${errYellow("warning:")} ${rel} was edited by hand — overwriting; state changes must go through events`);
    }
    writeFileSync(file, content);
    hashes[rel] = sha(content);
}

function sha(content: string): string
{
    return createHash("sha256").update(content).digest("hex");
}

function renderState(model: ProjectModel): string
{
    const lines: string[] = [GENERATED_NOTE, "", `# ${model.slug}`, ""];
    if (model.description !== undefined)
    {
        lines.push(model.description, "");
    }
    lines.push("## Goal", "", model.goal ?? "_not set_", "");
    section(lines, "Objectives", objectiveLines(model));
    section(lines, "Integration train", integrationLines(model));
    section(lines, "Proposed work", proposalSummaryLines(model));
    section(lines, "Decisions", decisionLines(model.decisions.filter((d) => d.status === "confirmed")));
    section(lines, "Proposed decisions", proposalLines(model.decisions));
    section(lines, "Conventions", model.conventions.map((c) => `- ${c.text} _(${c.id})_`));
    section(lines, "Work in progress", model.works.filter((w) => w.status === "active").map(workLine));
    section(lines, "Blocked", model.works.filter((w) => w.status === "blocked").map(blockedLine));
    section(lines, "Next", model.works.filter((w) => w.status === "next").map((w) => `- **${w.id}** ${w.outcome}`));
    section(lines, "Open questions", model.openQuestions.map((q) => `- ${q}`));
    section(lines, "Health", model.health.map((h) => `- ${h}`));
    return lines.join("\n").replace(/\n+$/, "\n");
}

function section(lines: string[], title: string, items: string[]): void
{
    if (items.length === 0)
    {
        return;
    }
    lines.push(`## ${title}`, "", ...items, "");
}

// The long-term goal above stays exactly where it is: an objective is a
// time-boxed target beside it, never a replacement for it.
function objectiveLines(model: ProjectModel): string[]
{
    const lines: string[] = [];
    for (const objective of openObjectives(model.goals))
    {
        const box = [objective.horizon, objective.target === undefined ? "" : `target ${objective.target}`]
            .filter((part) => part !== undefined && part !== "").join(", ");
        const proposed = objective.status === "proposed" ? " _(proposed)_" : "";
        lines.push(`- **${objective.id}** ${objective.outcome}${box === "" ? "" : ` (${box})`} — ` +
            `${objective.state}: ${objective.reason}${proposed}`);
        for (const milestone of objective.milestones)
        {
            lines.push(`  - **${milestone.id}** ${milestone.outcome}` +
                `${milestone.target === undefined ? "" : ` (target ${milestone.target})`} — ${milestone.state}: ${milestone.reason}`);
        }
    }
    return lines;
}

function proposalSummaryLines(model: ProjectModel): string[]
{
    return openProposals(model.goals).map((proposal) =>
        `- ${proposal.outcome} → ${proposal.milestone ?? proposal.objective} — ${proposal.confidence} confidence, ` +
        `${proposal.capacity}, expires ${proposal.expires} _(\`self work accept ${proposal.id.slice(0, 8)}\`)_`);
}

function decisionLines(decisions: DecisionState[]): string[]
{
    return decisions.map((decision) =>
    {
        const why = decision.why === undefined ? "" : ` — ${decision.why}`;
        return `- ${decision.text}${why} _(${day(decision.ts)}, ${decision.id})_`;
    });
}

function proposalLines(decisions: DecisionState[]): string[]
{
    return decisions
        .filter((decision) => decision.status === "proposed" && !decision.expired)
        .map((decision) => `- ${decision.text} _(proposed ${day(decision.ts)} — \`self decide confirm ${decision.id}\`)_`);
}

function workLine(work: WorkState): string
{
    const latest = work.reports[work.reports.length - 1];
    const report = latest === undefined ? "" : ` — ${latest.text}`;
    const next = work.next === undefined ? "" : ` (next: ${work.next})`;
    return `- **${work.id}** ${work.outcome}${report}${next}`;
}

function blockedLine(work: WorkState): string
{
    const why = work.blockedWhy === undefined ? "" : `: ${work.blockedWhy}`;
    return `- **${work.id}** ${work.outcome} — waiting on ${work.blockedOn}${why}`;
}

export function renderObjectiveBody(objective: ObjectiveState): string
{
    const lines: string[] = [`# ${objective.id} — ${objective.outcome}`, "", `- Status: ${objective.status}`,
        `- Target state: ${objective.state} — ${objective.reason}`, `- Revision: ${objective.revision}`];
    if (objective.horizon !== undefined || objective.target !== undefined)
    {
        lines.push(`- Timebox: ${objective.horizon ?? "unset"}${objective.target === undefined ? "" : `, target ${objective.target}`}`);
    }
    if (objective.priority !== undefined)
    {
        lines.push(`- Priority: ${objective.priority}`);
    }
    lines.push(`- Progress: ${objective.met} of ${objective.total} exit criteria covered`);
    if (objective.supersedes.length > 0)
    {
        lines.push(`- Supersedes: ${objective.supersedes.join(", ")}`);
    }
    if (objective.supersededBy !== undefined)
    {
        lines.push(`- Superseded by: ${objective.supersededBy}`);
    }
    lines.push("");
    bullets(lines, "Success criteria", objective.success);
    bullets(lines, "Stop criteria", objective.stop);
    bullets(lines, "Revision history", objective.history.map((entry) => `revision ${entry.revision} on ${day(entry.ts)} — ${entry.why}`));
    for (const milestone of objective.milestones)
    {
        lines.push(`## Milestone ${milestone.id}`, "", renderMilestoneBody(milestone, objective).split("\n").slice(2).join("\n"));
    }
    return lines.join("\n").replace(/\n+$/, "\n");
}

export function renderMilestoneBody(milestone: MilestoneState, objective: ObjectiveState): string
{
    const lines: string[] = [`# ${milestone.id} — ${milestone.outcome}`, "",
        `- Objective: ${objective.id} ${objective.outcome}`,
        `- State: ${milestone.state} — ${milestone.reason}`,
        `- Revision: ${milestone.revision} (objective revision ${objective.revision})`];
    if (milestone.target !== undefined)
    {
        lines.push(`- Target: ${milestone.target}`);
    }
    if (milestone.after.length > 0)
    {
        lines.push(`- After: ${milestone.after.join(", ")}`);
    }
    lines.push(`- Critical path: ${milestone.criticalPath ? "yes" : "no"}`);
    lines.push(`- Work: ${milestone.works.length === 0 ? "none linked" : milestone.works.join(", ")}`);
    if (milestone.evidence.length > 0)
    {
        lines.push(`- Evidence: ${milestone.evidence.join(", ")}`);
    }
    if (milestone.reached !== undefined)
    {
        lines.push(`- Reached: ${reachedLine(milestone.reached)}`);
    }
    if (milestone.reaffirmed !== undefined)
    {
        lines.push(`- Rechecked: ${reachedLine(milestone.reaffirmed)}`);
    }
    lines.push("");
    bullets(lines, "Exit criteria", exitLines(milestone));
    bullets(lines, "Coverage", milestone.coverage.map(coverageLine));
    return lines.join("\n").replace(/\n+$/, "\n");
}

function exitLines(milestone: MilestoneState): string[]
{
    return milestone.exit.map((criterion) =>
    {
        const state = criterion.dropped === true ? "dropped"
            : milestone.met.includes(criterion.id) ? "covered" : "open";
        return `${criterion.id} — ${criterion.text} _(${state})_`;
    });
}

function reachedLine(reached: Reached): string
{
    return `${day(reached.ts)} against objective revision ${reached.objectiveRevision}` +
        `/milestone revision ${reached.milestoneRevision}, criteria ${reached.criteria.join(", ")}` +
        `${reached.evidence.length === 0 ? "" : `, evidence ${reached.evidence.join(", ")}`}`;
}

function coverageLine(coverage: Coverage): string
{
    const from = [coverage.work, ...coverage.commits].filter((part) => part !== undefined).join(" ");
    return `${coverage.criterion} on ${day(coverage.ts)} — ${coverage.why}` +
        `${from === "" ? "" : ` [${from}]`} _(${coverage.recheck === true ? "rechecked at " : ""}` +
        `revision ${coverage.objectiveRevision}/${coverage.milestoneRevision})_`;
}

function contributionLines(work: WorkState, model: ProjectModel): string[]
{
    return contributionsOf(model.goals, work).map((item) =>
        `${item.id} ${item.outcome} (${item.state}${item.criticalPath ? ", critical path" : ""})`);
}

function bullets(lines: string[], title: string, items: string[]): void
{
    if (items.length > 0)
    {
        lines.push(`## ${title}`, "", ...items.map((item) => `- ${item}`), "");
    }
}

function renderWork(work: WorkState, model: ProjectModel, verdicts: Record<string, Verdict>): string
{
    return GENERATED_NOTE + "\n\n" + renderWorkBody(work, model, verdicts);
}

export function renderWorkBody(work: WorkState, model: ProjectModel, verdicts: Record<string, Verdict> = {}): string
{
    const lines: string[] = [`# ${work.id} — ${work.outcome}`, "", `- Status: ${work.status}`];
    const contributes = contributionLines(work, model);
    if (contributes.length > 0)
    {
        lines.push(`- Contributes to: ${contributes.join("; ")}`);
    }
    if (work.status === "blocked")
    {
        lines.push(`- Blocked on: ${work.blockedOn}${work.blockedWhy === undefined ? "" : ` — ${work.blockedWhy}`}`);
    }
    if (work.next !== undefined)
    {
        lines.push(`- Next action: ${work.next}`);
    }
    if (work.branches.length > 0)
    {
        lines.push(`- Branches: ${work.branches.join(", ")}`);
    }
    if (work.evidence.length > 0)
    {
        const marked = work.evidence.map((hash) => verdicts[hash] === undefined ? hash : `${hash} (${verdicts[hash]})`);
        lines.push(`- Evidence: ${marked.join(", ")}`);
    }
    if (work.artifacts.length > 0)
    {
        lines.push(`- Artifacts: ${work.artifacts.map((a) => `${a.id} ${a.name}`).join(", ")}`);
    }
    lines.push("");
    if (work.reports.length > 0)
    {
        lines.push("## Reports (latest first)", "");
        for (const report of [...work.reports].reverse())
        {
            const commits = report.commits.length > 0 ? ` [${report.commits.join(", ")}]` : "";
            if (report.text.includes("\n"))
            {
                lines.push(`### ${day(report.ts)}${commits}`, "", report.text, "");
            }
            else
            {
                lines.push(`- ${day(report.ts)} — ${report.text}${commits}`);
            }
        }
        lines.push("");
    }
    return lines.join("\n").replace(/\n+$/, "\n");
}

function day(ts: string): string
{
    return ts.slice(0, 10);
}
